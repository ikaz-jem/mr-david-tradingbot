export function paystackLiveApproved(env: Partial<Record<"BILLING_LIVE_ENABLED" | "PAYSTACK_MERCHANT_APPROVED" | "PAYSTACK_WEBHOOK_CONFIRMED", string>> = {
  BILLING_LIVE_ENABLED: process.env.BILLING_LIVE_ENABLED,
  PAYSTACK_MERCHANT_APPROVED: process.env.PAYSTACK_MERCHANT_APPROVED,
  PAYSTACK_WEBHOOK_CONFIRMED: process.env.PAYSTACK_WEBHOOK_CONFIRMED,
}) {
  return env.BILLING_LIVE_ENABLED === "true"
    && env.PAYSTACK_MERCHANT_APPROVED === "true"
    && env.PAYSTACK_WEBHOOK_CONFIRMED === "true";
}
