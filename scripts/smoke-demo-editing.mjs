async function post(context, path, data, expected = 200) {
  const response = await context.request.post(path, { headers, data });
  const result = await response.json();
  assert.equal(response.status(), expected, path + " " + JSON.stringify(result));
  return result;
}
async function login(context, role) {
  const csrf = await (await context.request.get("/api/auth/csrf")).json();
  await context.request.post("/api/auth/callback/credentials", { headers, form: { csrfToken: csrf.csrfToken, demoRole: role, callbackUrl: base, json: "true" } });
  const session = await (await context.request.get("/api/auth/session")).json();
  assert.equal(session.user.role, role); return session.user;
}
